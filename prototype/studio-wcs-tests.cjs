const assert=require('node:assert/strict');
const {validate}=require('./core-path-data.cjs');
const {attachWorkCoordinates}=require('./studio-facing-model.cjs');
const raw=require('./rust-facing-demo.json');
const project={stock:{x:120,y:80,z:12},origin:{x:15,y:20,z:12,rotation:270,reverseZ:true},wcs:'G56'};
const computed=attachWorkCoordinates(raw,project);
assert.equal(computed.work_coordinates.moves.length,raw.moves.length);
assert.equal(computed.work_coordinates.system,'G56');
assert.deepEqual(computed.work_coordinates.start,[20,25,-5]);
assert.deepEqual(computed.work_coordinates.moves[1].to,[20,25,1]);
assert.equal(validate(computed),computed);
const change=fn=>{const copy=structuredClone(computed);fn(copy);assert.throws(()=>validate(copy));};
change(d=>{d.work_coordinates.start[0]+=2;});
change(d=>{d.work_coordinates.origin_local[1]=90;});
change(d=>{d.work_coordinates.moves[0].to[2]=999;});
change(d=>{d.work_coordinates.moves[1].motion='rapid';});
change(d=>{d.work_coordinates.reverse_z=false;});
change(d=>{d.work_coordinates.moves.pop();});
change(d=>{d.work_coordinates.rotation_degrees=45;});
change(d=>{d.work_coordinates.system='G60';});
console.log('WCS path metadata, consistency with Rust local moves, and tampering rejection passed.');
